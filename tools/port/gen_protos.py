#!/usr/bin/env python3
"""Arduino's builder prepends function prototypes to a sketch; plain C++ needs them written out. Reads the app .cpp, writes the prototypes of its
top-level function definitions (the one-line-signature kind this code base uses) to a header the app includes right before its first function.
Default arguments move to the prototype and are stripped from the definition's copy.   gen_protos.py in.cpp out.h"""
import re, sys
src = open(sys.argv[1], encoding='utf-8').read().split('\n')
pat = re.compile(r'^(?!#|//|\s|\}|typedef|struct|class|enum|namespace|static const [^(]*=|const [^(]*=|extern )((?:static\s+|inline\s+|IRAM_ATTR\s+)*[A-Za-z_][\w:<>\*&]*(?:\s+[\w:<>\*&]+)*?\s+\**\s*([A-Za-z_]\w*)\s*\(([^;{}]*)\))\s*\{.*$')
out, seen = [], set()
for l in src:
    m = pat.match(l)
    if m and m.group(2) not in ('if', 'for', 'while', 'switch', 'setup', 'loop', 'main', 'app_main'):
        sig = m.group(1).strip()
        sig = re.sub(r'\bIRAM_ATTR\s+', '', sig)
        if sig not in seen: seen.add(sig); out.append(sig + ';')
open(sys.argv[2], 'w').write('// generated by tools/port/gen_protos.py - do not edit\n#pragma once\n' + '\n'.join(out) + '\n')
print(len(out), 'prototypes')
