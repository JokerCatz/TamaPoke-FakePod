#!/usr/bin/env python3
"""Subsets GNU Unifont (16 px bitmaps) to exactly the characters the Traditional Chinese UI uses and writes idf/components/gfx_compat/src/font_zh_unifont16.inc.
Characters = every char of the ZH rows of i18n.cpp (strings + medals) + the 151 zh names of tools/dex_names.py + printable ASCII.
  python3 tools/gen_zh_font.py /path/to/unifont_all-*.hex
Unifont: (c) the GNU Unifont maintainers; fonts under SIL OFL 1.1 (and GPL-2+ with the font embedding exception), see idf/components/gfx_compat/LICENSE-Unifont.txt."""
import ast, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import test_i18n_formats as T
ROOT = os.path.join(HERE, '..')
src = open(os.path.join(ROOT, 'i18n.cpp'), encoding='utf-8').read()
zi = T.LANGS.index('ZH')
chars = set(chr(c) for c in range(0x20, 0x7F))
for name in ('STRINGS', 'MED_NAME', 'MED_LBL', 'MED_DSC'):
    for s in T.extract_table(src, name, len(T.LANGS))[zi]:
        chars |= set(ast.literal_eval(s))
ns = {}; exec(open(os.path.join(HERE, 'dex_names.py'), encoding='utf-8').read(), ns)
for d in ns['LOCAL_NAMES'].values():
    chars |= set(d.get('zh', ''))
hexf = {}
for line in open(sys.argv[1], encoding='ascii'):
    cp, bits = line.strip().split(':')
    c = int(cp, 16)
    if chr(c) in chars: hexf[c] = bytes.fromhex(bits)
missing = sorted(chars - {chr(c) for c in hexf})
if missing: sys.exit(f'Unifont has no glyph for: {missing}')
out = ['// generated by tools/gen_zh_font.py from GNU Unifont (OFL 1.1 / GPL-2+ with font exception) - do not edit',
       f'// {len(hexf)} glyphs, 16 px cell (8 or 16 wide), baseline at row 14',
       '// { codepoint, advance, ink x0, ink x1, ink y0, ink y1, 16 rows of bitmap (MSB = leftmost; 2 bytes per row when advance == 16) }',
       'struct ZhGlyph { uint16_t cp; uint8_t adv, x0, x1, y0, y1; uint8_t rows[32]; };',
       'static const ZhGlyph ZH_GLYPHS[] = {']
for c in sorted(hexf):
    b = hexf[c]; adv = 8 if len(b) == 16 else 16
    rows = [int.from_bytes(b[i * (adv // 8):(i + 1) * (adv // 8)], 'big') for i in range(16)]
    xs = [x for r in rows for x in range(adv) if r >> (adv - 1 - x) & 1]
    ys = [y for y, r in enumerate(rows) if r]
    x0, x1, y0, y1 = (min(xs), max(xs), min(ys), max(ys)) if xs else (0, 0, 0, 0)
    data = list(b) + [0] * (32 - len(b))
    out.append(f'  {{ 0x{c:04X}, {adv}, {x0}, {x1}, {y0}, {y1}, {{' + ','.join(f'0x{v:02X}' for v in data) + '} },')
out.append('};')
open(os.path.join(ROOT, 'idf', 'components', 'gfx_compat', 'src', 'font_zh_unifont16.inc'), 'w').write('\n'.join(out) + '\n')
print(len(hexf), 'glyphs;', sum(1 for c in hexf if len(hexf[c]) == 32), 'full-width')
