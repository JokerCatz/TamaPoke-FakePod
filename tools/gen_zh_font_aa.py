#!/usr/bin/env python3
"""Rasterises the characters of the Chinese UI from Noto Sans CJK (TC and SC, SIL OFL 1.1) into small anti-aliased (4 grey levels, 2 bits per pixel) bitmaps and writes
idf/components/gfx_compat/src/font_zh_aa.inc. Used for body text (text scale 1 of the CJK path); bigger text keeps scaling the Unifont pixel glyphs.
  python3 tools/gen_zh_font_aa.py --tc NotoSansTC-Regular.otf --sc NotoSansSC-Regular.otf [--size 22]
Needs Pillow. The embedded data are bitmaps derived from Noto Sans CJK: keep the OFL text with them (idf/components/gfx_compat/LICENSE-NotoSansCJK-OFL.txt)."""
import argparse, os, sys
from PIL import Image, ImageDraw, ImageFont
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import gen_zh_font as G
ap = argparse.ArgumentParser(); ap.add_argument('--tc', required=True); ap.add_argument('--sc', required=True); ap.add_argument('--size', type=int, default=22)
a = ap.parse_args()
N = a.size
BASE = round(N * 0.82)                    # baseline row inside the cell (Noto's ascender is 0.88 em; this leaves room for the descenders)
chars = sorted(G.collect())
out = ['// generated by tools/gen_zh_font_aa.py from Noto Sans CJK TC / SC (SIL OFL 1.1) - do not edit',
       f'// {len(chars)} characters per font, em = {N} px, baseline {BASE} px below the cell top; 2 bits per pixel (0 = clear .. 3 = solid), rows packed MSB first',
       'struct AaGlyph { uint16_t cp; uint8_t adv, w, h; int8_t xo, yo; uint32_t off; };   // ink box w*h at (xo, yo) from the pen, yo = rows above the baseline (negative = above)',
       f'#define AA_EM {N}', f'#define AA_BASE {BASE}']
for tag, path in (('TC', a.tc), ('SC', a.sc)):
    font = ImageFont.truetype(path, N)
    blob = bytearray(); rows = []
    for ch in chars:
        im = Image.new('L', (N * 3, N * 3), 0); d = ImageDraw.Draw(im)
        ox, oy = N, N * 2
        d.text((ox, oy), ch, font=font, fill=255, anchor='ls')
        adv = round(font.getlength(ch))
        bb = im.getbbox()
        if bb is None:                                         # space
            rows.append((ord(ch), adv, 0, 0, 0, 0, len(blob))); continue
        x0, y0, x1, y1 = bb; w, h = x1 - x0, y1 - y0
        pix = [min(3, (im.getpixel((x, y)) + 42) // 85) for y in range(y0, y1) for x in range(x0, x1)]
        off = len(blob)
        for i in range(0, len(pix), 4):
            q = pix[i:i + 4] + [0] * (4 - len(pix[i:i + 4]))
            blob.append(q[0] << 6 | q[1] << 4 | q[2] << 2 | q[3])
        rows.append((ord(ch), adv, w, h, x0 - ox, y0 - oy, off))
    out.append(f'static const uint8_t AA_{tag}_DATA[] = {{')
    for i in range(0, len(blob), 24): out.append('  ' + ','.join(f'0x{b:02X}' for b in blob[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const AaGlyph AA_{tag}[] = {{')
    for cp, adv, w, h, xo, yo, off in rows: out.append(f'  {{ 0x{cp:04X}, {adv}, {w}, {h}, {xo}, {yo}, {off} }},')
    out.append('};')
    print(tag, len(rows), 'glyphs', len(blob), 'bytes')
    if tag == 'TC':
        capA = next(r for r in rows if r[0] == ord('A'))
        DY = -capA[5] - 12            # app code measures the ascent from 'A' at scale 1 and multiplies it by the scale: keep Unifont's 12
        out.insert(4, f'#define AA_DY {DY}   // draw AA glyphs this many rows lower so that the cap height of A matches Unifont (12 px above the pen)')
open(os.path.join(HERE, '..', 'idf', 'components', 'gfx_compat', 'src', 'font_zh_aa.inc'), 'w').write('\n'.join(out) + '\n')
